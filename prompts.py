def parse_command(text: str) -> Optional[tuple[str, dict]]:
    """
    解析用户指令，返回 (skill_name, params) 或 None

    容错：合并多余空格、忽略大小写。支持省略话题（自动选题）、省略参数（使用默认值）。

    支持格式：
      法考 [【考点】] [A/B] [1-4]
      小红书 [[【话题】/《标题》]]
      公众号 [[【话题】/《标题》]]
      劳动法 [[【话题】] [A/B] [是/否]]
    """
    # 预处理：合并多余空格
    text = re.sub(r'\s+', ' ', text.strip())

    # 法考（关键词匹配，参数可省略）
    if '法考' in text:
        track = "A"
        strategy = "1"
        # 提取赛道
        m = re.search(r'([ABab])', text)
        if m:
            track = m.group(1).upper()
        # 提取策略
        m = re.search(r'([1-4])', text)
        if m:
            strategy = m.group(1)
        # 提取考点（如果有【】）
        topic = None
        m = re.search(r'【(.+?)】', text)
        if m:
            topic = m.group(1)
        return "lawexam", {"track": track, "strategy": strategy, "topic": topic}

    # ADHD 小红书
    if '小红书' in text or (text.upper() == 'ADHD'):
        # 提取赛道：A=成人 B=儿童/亲子 C=夫妻/伴侣 D=职场
        adhd_track = "A"
        if re.search(r'[Bb]', text) or any(k in text for k in ['儿童', '孩子', '亲子', '小孩']):
            adhd_track = "B"
        elif re.search(r'[Cc]', text) or any(k in text for k in ['夫妻', '伴侣', '婚姻', '关系']):
            adhd_track = "C"
        elif re.search(r'[Dd]', text) or any(k in text for k in ['职场', '工作', '上班']):
            adhd_track = "D"
        # 带标题《》
        m = re.search(r'《(.+?)》', text)
        if m:
            return "adhd_xhs", {"input": m.group(1), "mode": "title", "track": adhd_track}
        # 带话题【】
        m = re.search(r'【(.+?)】', text)
        if m:
            return "adhd_xhs", {"input": m.group(1), "mode": "topic", "track": adhd_track}
        # 无话题 → 自动选题
        return "adhd_xhs", {"input": None, "mode": "auto", "track": adhd_track}

    # ADHD 公众号贴图（长词优先：必须在「公众号」之前匹配，否则会被文章档抢走）
    if '公众号贴图' in text:
        adhd_track = "A"
        if re.search(r'[Bb]', text) or any(k in text for k in ['儿童', '孩子', '亲子', '小孩']):
            adhd_track = "B"
        elif re.search(r'[Cc]', text) or any(k in text for k in ['夫妻', '伴侣', '婚姻', '关系']):
            adhd_track = "C"
        elif re.search(r'[Dd]', text) or any(k in text for k in ['职场', '工作', '上班']):
            adhd_track = "D"
        m = re.search(r'《(.+?)》', text)
        if m:
            return "adhd_gzh_img", {"input": m.group(1), "mode": "title", "track": adhd_track}
        m = re.search(r'【(.+?)】', text)
        if m:
            return "adhd_gzh_img", {"input": m.group(1), "mode": "topic", "track": adhd_track}
        return "adhd_gzh_img", {"input": None, "mode": "auto", "track": adhd_track}

    # ADHD 公众号
    if '公众号' in text:
        # 提取赛道：A=成人 B=儿童/亲子 C=夫妻/伴侣 D=职场
        adhd_track = "A"
        if re.search(r'[Bb]', text) or any(k in text for k in ['儿童', '孩子', '亲子', '小孩']):
            adhd_track = "B"
        elif re.search(r'[Cc]', text) or any(k in text for k in ['夫妻', '伴侣', '婚姻', '关系']):
            adhd_track = "C"
        elif re.search(r'[Dd]', text) or any(k in text for k in ['职场', '工作', '上班']):
            adhd_track = "D"
        m = re.search(r'《(.+?)》', text)
        if m:
            return "adhd_gzh", {"input": m.group(1), "mode": "title", "track": adhd_track}
        m = re.search(r'【(.+?)】', text)
        if m:
            return "adhd_gzh", {"input": m.group(1), "mode": "topic", "track": adhd_track}
        return "adhd_gzh", {"input": None, "mode": "auto", "track": adhd_track}

    # 劳动法
    if '劳动法' in text:
        track = "A"
        inject = True
        # 提取赛道
        m = re.search(r'([ABab])', text)
        if m:
            track = m.group(1).upper()
        # 提取植入
        if '否' in text:
            inject = False
        # 提取话题（如果有【】）
        topic = None
        m = re.search(r'【(.+?)】', text)
        if m:
            topic = m.group(1)
        return "laborlaw", {"topic": topic, "track": track, "inject": inject}

    return None


